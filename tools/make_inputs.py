#!/usr/bin/env python3
"""Write the stdin fixtures used by the GDB evidence scripts into /tmp/lab3-inputs.

The three payload-derived fixtures are generated by running the actual payload
scripts, so they can never drift from the committed exploits.
"""
import os
import struct
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = "/tmp/lab3-inputs"
os.makedirs(OUT, exist_ok=True)


def w(name, data):
    with open(os.path.join(OUT, name), "wb") as fh:
        fh.write(data)


def from_payload(name, script):
    """Run a payload generator and capture its stdout bytes as the fixture."""
    proc = subprocess.run([sys.executable, os.path.join(ROOT, script)],
                          cwd=ROOT, capture_output=True, timeout=15)
    if proc.returncode != 0:
        raise SystemExit(f"{script} failed (rc={proc.returncode}):\n"
                         + proc.stderr.decode("utf-8", "replace"))
    w(name, proc.stdout)


w("eight.bin", b"ABCDEFGH\n")
w("arith.bin", b"1+1\n")
w("empty.bin", b"\n")

# same bytes the payload scripts emit (derived from them, never duplicated)
from_payload("shellcode.bin", "payload_dark.py")
from_payload("canary.bin", "payload_canary.py")
from_payload("overflow_system.bin", "payload.py")

# dark-log stack-smash control: a valid len keeps the memcpy in-frame, but the
# canary bytes themselves are overwritten, so the return check must abort.
w("smash.bin", b"A" * 256 + struct.pack("<I", 0xA0) + b"B" * 20 + b"C" * 8 + b"\n")

print("wrote fixtures to", OUT)
